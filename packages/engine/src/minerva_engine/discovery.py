"""Adaptive discovery of conserved quantities of a Lagrangian or Hamiltonian system.

`invariants.py` solves for a constant of motion in *one* ansatz that the caller must choose. This module
chooses the ansatz: it searches a deterministic ladder of nested families and expands it until a verified
set of constants is found, the maximum possible number of independent constants is reached, or a declared
budget is spent. Nothing about any particular system is known to it.

The method, per family (a tier):

    I(q, v, t) = sum_i c_i phi_i(q, v, t)        phi_i = f(q) * (monomial in v of degree <= d) * t^j

* `f` is a product of powers `q^a` (negative powers only for coordinates that occur in a denominator of the
  equations of motion), or of `cos`/`sin` up to a harmonic for an angle. A coordinate is an angle if it was
  declared one, if the equations contain it only through `cos` and `sin`, or if it is cyclic (the equations
  do not contain it): conservation does not depend on periodicity, so trigonometric functions of a cyclic
  coordinate are always a legitimate family.
* `dI/dt = 0` on the equations of motion is linear in `c_i`. Each basis function's derivative is cleared
  of denominators and expanded once (cached across tiers); the determining equations are the coefficients
  of each monomial, and the nullspace is computed exactly over the field of rational functions of the
  parameters. No floating point is involved.
* The nullspace is reduced modulo the algebra generated by the constants already known or found (products
  of up to four of them that lie in the tier's family), so a trivial combination of earlier quantities is
  never reported as a discovery.
* Every remaining direction is verified on the equations of motion, symbolically and at random numerical
  points (`flow.Flow.verify`); a candidate that fails is dropped and counted, never shown.
* The functional rank of everything found, and the algebraic relations among it, are established by
  `independence.py` (proved bounds only).

What this does and does not establish: a tier's result is *complete within that tier's family* (the
nullspace is the whole solution space), and nothing is claimed outside it. Absence of a constant after the
last tier proves nothing about larger families, other function classes, or special parameter values. The
report lists the families searched, the ones skipped and why, and the generic-parameter assumptions.
"""

