def _chain(setup: _Setup, budget: Budget, pins: Pins | None) -> tuple[list[TierKey], list[str]]:
    """The deterministic ladder: a nested chain of families, from a schedule that raises the degree in the
    velocities, the power bound and the harmonics in turn (and time last), skipping a step whose family
    would exceed the unknown cap. Returns the chain and the steps that were refused."""
    refused: list[str] = []
    has_trig = bool(setup.trig_idx)
    if pins is not None and any(
        x is not None for x in (pins.degree, pins.power_bound, pins.harmonics, pins.time_degree)
    ):
        key = TierKey(
            pins.degree or 2,
            3 if pins.power_bound is None else pins.power_bound,
            pins.harmonics or 1,
            pins.time_degree or 0,
        )
        return [key], []
    max_time = budget.max_time
    if setup.time_in_rates:
        max_time = max(max_time, 2 if budget.name != "quick" else 1)
    limits = {
        "d": budget.max_degree,
        "P": budget.max_power,
        "H": budget.max_harmonics if has_trig else 1,
        "T": max_time,
        "C": 2 if setup.cyclic_idx else 0,
    }
    key = TierKey(1, 1, 1, 0)
    chain = [key]
    schedule = ["d", "P", "P", "C", "d", "H", "P", "d", "P", "C", "T", "T"]
    label = {
        "d": "momentum degree",
        "P": "power bound",
        "H": "harmonics",
        "T": "powers of t",
        "C": "powers of the cyclic coordinates",
    }

    def bump(k: TierKey, step: str) -> TierKey | None:
        if step == "d" and k.degree < limits["d"]:
            return replace(k, degree=k.degree + 1)
        if step == "P" and k.power < limits["P"]:
            return replace(k, power=k.power + 1)
        if step == "H" and k.harmonics < limits["H"]:
            return replace(k, harmonics=k.harmonics + 1)
        if step == "T" and k.time < limits["T"]:
            return replace(k, time=k.time + 1)
        if step == "C" and k.cyclic < limits["C"]:
            return replace(k, cyclic=k.cyclic + 1)
        return None

    if setup.unknowns(key) > budget.max_unknowns:
        return [], [f"the smallest family already has {setup.unknowns(key)} unknown coefficients"]
    for step in schedule:
        nxt = bump(key, step)
        if nxt is None:
            continue
        size = setup.unknowns(nxt)
        if size > budget.max_unknowns:
            refused.append(
                f"raising the {label[step]} to {getattr(nxt, {'d': 'degree', 'P': 'power', 'H': 'harmonics', 'T': 'time', 'C': 'cyclic'}[step])} "
                f"needs {size} unknown coefficients (limit {budget.max_unknowns})"
            )
            if step == "d":
                # Not nested: a higher degree with a smaller power bound is still searched if it fits.
                for lower in range(key.power - 1, 0, -1):
                    narrow = replace(nxt, power=lower)
                    if setup.unknowns(narrow) <= budget.max_unknowns:
                        chain.append(narrow)
                        break
            continue
        key = nxt
        chain.append(key)
    return chain, refused


def _momentum_degree(setup: _Setup, poly: sp.Expr) -> int:
    shifted = sp.expand(poly * setup.shift)
    try:
        return int(sp.Poly(shifted, *setup.flow.v).total_degree())
    except sp.PolynomialError:
        return 0


def _primitive(vector: dict[int, sp.Expr], columns: list[sp.Expr]) -> tuple[sp.Expr, list[sp.Expr]]:
    """Sum of v_j * column_j with coefficients scaled to coprime polynomials in the parameters, and the
    parameter polynomials that were divided or multiplied out (the generic-parameter assumptions)."""
    coefficients = {j: sp.together(sp.sympify(v)) for j, v in vector.items()}
    lcm = sp.Integer(1)
    for value in coefficients.values():
        lcm = sp.lcm(lcm, sp.fraction(value)[1])
    scaled = {j: sp.cancel(value * lcm) for j, value in coefficients.items()}
    gcd = sp.gcd_list(list(scaled.values()))
    if gcd != 0:
        scaled = {j: sp.cancel(value / gcd) for j, value in scaled.items()}
    conditions = [f for f in (lcm, gcd) if f != 0 and not f.is_number]
    return sp.Add(*[value * columns[j] for j, value in scaled.items()]), conditions


