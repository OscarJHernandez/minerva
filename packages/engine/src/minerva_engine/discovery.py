class _Setup:
    """The polynomial setting of a flow: variables, substituted rates, derivative and tier columns."""

    def __init__(self, flow: Flow, declared_angles: list[str], budget: Budget, pins: Pins | None):
        self.flow = flow
        n = flow.n
        self.n = n
        q, v = flow.q, flow.v
        index = {s: i for i, s in enumerate(q)}
        rates = [sp.together(sp.expand_trig(r)) for r in [*flow.q_rate, *flow.v_rate]]

        trig_args: set[sp.Symbol] = set()
        for e in rates:
            for atom in e.atoms(sp.cos, sp.sin):
                arg = atom.args[0]
                if arg not in index:
                    raise _Unsupported(
                        "A cos or sin has an argument that is not a single coordinate, even after "
                        "expansion, so it cannot be a basis function."
                    )
                trig_args.add(arg)
        declared = {q[i] for i, name in enumerate(flow.coordinates) if name in declared_angles}
        trig_args |= declared
        taken = {s.name for s in flow.params} | {s.name for s in q + v} | {flow.t.name}

        def fresh(name: str) -> sp.Symbol:
            while name in taken:
                name += "_"
            taken.add(name)
            return sp.Symbol(name)

        cyclic = [
            i
            for i in range(n)
            if q[i] not in trig_args and not any(q[i] in e.free_symbols for e in rates)
        ]
        self.angle_idx = [i for i in range(n) if q[i] in trig_args]
        self.cyclic_idx = [i for i in cyclic if i not in self.angle_idx]
        self.trig_idx = sorted(self.angle_idx + self.cyclic_idx)
        self.cos_s = {i: fresh(f"c_{flow.coordinates[i]}") for i in self.trig_idx}
        self.sin_s = {i: fresh(f"s_{flow.coordinates[i]}") for i in self.trig_idx}
        self.trig_sub: dict[sp.Basic, sp.Symbol] = {}
        for i in self.angle_idx:
            self.trig_sub[sp.cos(q[i])] = self.cos_s[i]
            self.trig_sub[sp.sin(q[i])] = self.sin_s[i]
        rates = [sp.together(r.subs(self.trig_sub)) for r in rates]
        self.q_rate, self.v_rate = rates[:n], rates[n:]
        for e in rates:
            if any(q[i] in e.free_symbols for i in self.angle_idx) or e.atoms(sp.Function):
                raise _Unsupported(
                    "A declared or detected angle appears other than through cos and sin, or a function "
                    "other than those appears in the equations of motion."
                )
        self.plain_idx = [i for i in range(n) if i not in self.angle_idx]
        self.use_time = flow.t in set().union(*(e.free_symbols for e in rates)) or (
            pins.time_degree > 0 if pins and pins.time_degree is not None else budget.max_time > 0
        )
        self.time_in_rates = flow.t in set().union(*(e.free_symbols for e in rates))
        self.variables: list[sp.Symbol] = [q[i] for i in self.plain_idx] + list(v)
        self.variables += [self.cos_s[i] for i in self.trig_idx]
        self.variables += [self.sin_s[i] for i in self.trig_idx]
        if self.use_time:
            self.variables.append(flow.t)
        for e in rates:
            if not e.is_rational_function(*self.variables):
                raise _Unsupported(
                    "The equations of motion are not rational in the coordinates, the velocities or "
                    "momenta and the cos and sin of the angles (square roots and the like are not "
                    "searched)."
                )
        denominators = [sp.fraction(sp.together(e))[1] for e in rates]
        self.denom_idx = [
            i
            for i in self.plain_idx
            if i not in self.cyclic_idx and any(q[i] in d.free_symbols for d in denominators)
        ]
        self.denominator = sp.Integer(1)
        for d in denominators:
            self.denominator = sp.lcm(self.denominator, d)

        # Derivative of a polynomial variable along the flow.
        self.rate_of: dict[sp.Symbol, sp.Expr] = {}
        for i in self.plain_idx:
            self.rate_of[q[i]] = self.q_rate[i]
        for i in range(n):
            self.rate_of[v[i]] = self.v_rate[i]
        for i in self.trig_idx:
            self.rate_of[self.cos_s[i]] = -self.sin_s[i] * self.q_rate[i]
            self.rate_of[self.sin_s[i]] = self.cos_s[i] * self.q_rate[i]
        if self.use_time:
            self.rate_of[flow.t] = sp.Integer(1)
        self.field = sp.QQ.frac_field(*flow.params) if flow.params else sp.QQ
        self.back = {self.cos_s[i]: sp.cos(q[i]) for i in self.trig_idx} | {
            self.sin_s[i]: sp.sin(q[i]) for i in self.trig_idx
        }
        self.pmax = max(budget.max_power, pins.power_bound or 0 if pins else 0)
        self.shift = sp.Mul(*[q[i] ** self.pmax for i in self.denom_idx])
        self.clear = self.shift * self.denominator * sp.Mul(*[q[i] for i in self.denom_idx])
        self._deriv: dict[tuple[int, ...], dict[tuple[int, ...], sp.Expr]] = {}

    # -- families ---------------------------------------------------------------------------------------
    def trig_functions(self, i: int, harmonics: int) -> list[sp.Expr]:
        c, s = self.cos_s[i], self.sin_s[i]
        return [sp.Integer(1)] + [
            c**e * s**g for g in (0, 1) for e in range(0, harmonics + 1) if 1 <= e + g <= harmonics
        ]

    def functions(self, i: int, key: TierKey) -> list[sp.Expr]:
        q = self.flow.q[i]
        if i in self.angle_idx:
            return self.trig_functions(i, key.harmonics)
        if i in self.cyclic_idx:
            return self.trig_functions(i, key.harmonics) + [
                q**a for a in range(1, max(key.time, key.cyclic) + 1)
            ]
        low = -key.power if i in self.denom_idx else 0
        return [q**a for a in range(low, key.power + 1)]

    def velocity_monomials(self, degree: int) -> list[tuple[int, ...]]:
        monos = [a for a in itertools.product(range(degree + 1), repeat=self.n) if sum(a) <= degree]
        return monos

    def unknowns(self, key: TierKey) -> int:
        count = math.comb(self.n + key.degree, self.n) * (key.time + 1)
        for i in range(self.n):
            count *= len(self.functions(i, key))
        return count

    def describe(self, key: TierKey) -> str:
        names = self.flow.coordinates
        v_name = "velocities" if self.flow.system == "lagrangian" else "momenta"
        parts = [f"polynomials of degree at most {key.degree} in the {v_name}"]
        plain = [names[i] for i in self.plain_idx if i not in self.cyclic_idx]
        if plain:
            neg = [names[i] for i in self.denom_idx]
            text = f"powers of {', '.join(plain)} up to {key.power}"
            if neg:
                text += (
                    f" (down to -{key.power} for {', '.join(neg)}, which occur in a denominator)"
                )
            parts.append(text)
        trig = [names[i] for i in self.trig_idx]
        if trig:
            cyc = [names[i] for i in self.cyclic_idx]
            text = f"cos and sin of {', '.join(trig)} up to harmonic {key.harmonics}"
            if cyc:
                text += f" ({', '.join(cyc)} cyclic, treated as periodic)"
                if key.cyclic:
                    text += f" and powers of {', '.join(cyc)} up to {key.cyclic}"
            parts.append(text)
        if key.time:
            parts.append(f"powers of t up to {key.time}")
        return "; ".join(parts)

    def columns(self, key: TierKey) -> list[sp.Expr]:
        per = [self.functions(i, key) for i in range(self.n)]
        vm = self.velocity_monomials(key.degree)
        v = self.flow.v
        out: list[sp.Expr] = []
        for j in range(key.time + 1):
            tj = self.flow.t**j if j else sp.Integer(1)
            for combo in itertools.product(*per):
                f = sp.Mul(*combo) * tj
                for alpha in vm:
                    out.append(f * sp.Mul(*[v[i] ** alpha[i] for i in range(self.n)]))
        return out

    # -- polynomial plumbing ----------------------------------------------------------------------------
    def reduce_angles(self, expr: sp.Expr) -> sp.Expr:
        out = sp.expand(expr)
        for i in self.trig_idx:
            s, c = self.sin_s[i], self.cos_s[i]
            out = sp.expand(sp.rem(out, s**2 + c**2 - 1, s))
        return out

    def key_of(self, term: sp.Expr) -> tuple[int, ...]:
        poly = sp.Poly(sp.expand(term * self.shift), *self.variables)
        terms = poly.terms()
        if len(terms) != 1:
            raise sp.PolynomialError("a column is a single monomial")
        return tuple(terms[0][0])

    def total_derivative(self, expr: sp.Expr) -> sp.Expr:
        out = sp.Integer(0)
        for var, rate in self.rate_of.items():
            out += sp.diff(expr, var) * rate
        return out

    def derivative_terms(
        self, col: sp.Expr, key: tuple[int, ...]
    ) -> dict[tuple[int, ...], sp.Expr]:
        cached = self._deriv.get(key)
        if cached is not None:
            return cached
        raw = sp.cancel(sp.together(self.total_derivative(col) * self.clear))
        if not raw.is_polynomial(*self.variables):
            raise sp.PolynomialError("the derivative is not polynomial after clearing denominators")
        poly = sp.Poly(self.reduce_angles(raw), *self.variables)
        terms = {tuple(m): c for m, c in poly.terms()}
        self._deriv[key] = terms
        return terms

    def to_vector(
        self, expr: sp.Expr, column_index: dict[tuple[int, ...], int]
    ) -> dict[int, sp.Expr] | None:
        shifted = sp.expand(expr * self.shift)
        if not shifted.is_polynomial(*self.variables):
            return None
        vector: dict[int, sp.Expr] = {}
        for monom, coeff in sp.Poly(self.reduce_angles(shifted), *self.variables).terms():
            column = column_index.get(tuple(monom))
            if column is None:
                return None
            vector[column] = coeff
        return vector

    def context(self, gens: list[_Gen]) -> PolyContext:
        q = self.flow.q
        free = [
            q[i] for i in self.plain_idx if i not in self.cyclic_idx or self._uses_power(gens, i)
        ]
        free += list(self.flow.v)
        if self.use_time:
            free.append(self.flow.t)
        mixed = [
            self.flow.coordinates[i]
            for i in self.cyclic_idx
            if self._uses_power(gens, i)
            and any(
                self.cos_s[i] in g.poly.free_symbols or self.sin_s[i] in g.poly.free_symbols
                for g in gens
            )
        ]
        angles = [(self.cos_s[i], self.sin_s[i]) for i in self.trig_idx]
        return PolyContext(
            variables=self.variables,
            free=free,
            angles=angles,
            shift=self.shift,
            params=list(self.flow.params),
            reduce_angles=self.reduce_angles,
            mixed=mixed,
        )

    def _uses_power(self, gens: list[_Gen], i: int) -> bool:
        return any(self.flow.q[i] in g.poly.free_symbols for g in gens)


