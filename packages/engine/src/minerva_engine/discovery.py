@dataclass
class _Recorder:
    started: float
    events: list[SearchEvent] = field(default_factory=list)

    def emit(self, name: str, tier: int | None = None, **data: int | float | str | bool) -> None:
        self.events.append(
            SearchEvent(
                name=f"invariant_search.{name}",
                tier=tier,
                at_ms=int((time.monotonic() - self.started) * 1000),
                data=dict(data),
            )
        )


def _peak_mb() -> float:
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return round(peak / (1024 * 1024 if sys.platform == "darwin" else 1024), 1)


class _Unsupported(Exception):
    def __init__(self, message: str, cause: Cause = "unsupported_function") -> None:
        super().__init__(message)
        self.message = message
        self.cause: Cause = cause


@dataclass
class _Gen:
    id: str
    name: str
    shown: sp.Expr
    poly: sp.Expr
    kind: Literal["known", "new"]
    source: str
    tier: int | None
    degree: int
    verification: Verification | None
