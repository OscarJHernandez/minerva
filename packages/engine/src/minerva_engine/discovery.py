def discover(
    flow: Flow,
    declared_angles: list[str],
    budget_name: str,
    pins: Pins | None,
    limits: Limits,
    started: float | None = None,
) -> DiscoveryReport:
    started = time.monotonic() if started is None else started
    budget = BUDGETS[budget_name]
    deadline = started + DEADLINE_FRACTION * min(limits.timeout_seconds, budget.seconds * 1.2)
    rec = _Recorder(started)
    base: dict[str, Any] = {
        "system": flow.system,
        "function_latex": flow.function_latex,
        "coordinates": flow.coordinates,
        "budget": budget_name,
        "limitations": list(LIMITATIONS),
    }
    rec.emit(
        "started",
        system=flow.system,
        coordinates=flow.n,
        parameters=len(flow.params),
        budget=budget_name,
        time_dependent=flow.time_dependent,
    )
    try:
        setup = _Setup(flow, declared_angles, budget, pins)
    except _Unsupported as exc:
        rec.emit("completed", stop="unsupported", cause=exc.cause)
        return DiscoveryReport(
            status=Status.UNSUPPORTED,
            message=exc.message,
            cause=exc.cause,
            stop_reason="unsupported",
            events=rec.events,
            duration_ms=int((time.monotonic() - started) * 1000),
            peak_memory_mb=_peak_mb(),
            **base,
        )
    base["angles"] = [flow.coordinates[i] for i in setup.trig_idx]

    gens: list[_Gen] = []
    for item, expr in flow.known:
        converted = sp.expand(sp.expand_trig(sp.sympify(expr)).subs(setup.trig_sub))
        if any(flow.q[i] in converted.free_symbols for i in setup.angle_idx):
            continue
        gens.append(
            _Gen(
                id=f"C{len(gens) + 1}",
                name=item.name,
                shown=sp.sympify(expr),
                poly=converted,
                kind="known",
                source=item.kind,
                tier=None,
                degree=_momentum_degree(setup, converted),
                verification=item.verification,
                reason=item.reason,
            )
        )

    chain, refused = _chain(setup, budget, pins)
    max_possible = 2 * flow.n if (flow.time_dependent or setup.use_time) else 2 * flow.n - 1
    autonomous_cap = 2 * flow.n - 1  # time-independent constants of an autonomous system
    tiers: list[TierRecord] = []
    parameter_conditions: set[str] = set()
    dropped_total = 0
    stop_reason = "ladder_exhausted"
    skipped_tiers: list[str] = []
    notes: list[str] = []

    def lower_rank() -> int:
        ctx = setup.context(gens)
        if ctx.mixed or not gens:
            return 0
        return point_rank([g.poly for g in gens], ctx)[0]

    if not chain:
        rec.emit("completed", stop="resource_limit", cause="resource_limit")
        return DiscoveryReport(
            status=Status.RESOURCE_LIMIT,
            message=f"No family fits in the budget: {refused[0]}.",
            cause="resource_limit",
            stop_reason="unknown_cap",
            unexplored=refused,
            events=rec.events,
            duration_ms=int((time.monotonic() - started) * 1000),
            peak_memory_mb=_peak_mb(),
            **base,
        )

    # Only the quick budget stops as soon as the maximum number of independent constants is reached;
    # the others finish the ladder, because further verified constants (functionally dependent on the
    # ones found, not polynomial combinations of them) are still worth reporting.
    stop_at_rank = (
        autonomous_cap
        if budget_name == "quick" and not (flow.time_dependent or setup.time_in_rates)
        else None
    )
    maximum_noted = False
    for index, key in enumerate(chain):
        if stop_at_rank is not None and key.time == 0 and lower_rank() >= stop_at_rank:
            stop_reason = "maximal_independent_set"
            skipped_tiers = [setup.describe(k) for k in chain[index:]]
            rec.emit("family_expanded", index, reason="maximum_rank_reached", rank=lower_rank())
            break
        if time.monotonic() > deadline:
            stop_reason = "time_budget"
            skipped_tiers = [setup.describe(k) for k in chain[index:]]
            break
        tier_started = time.monotonic()
        columns = setup.columns(key)
        unknowns = len(columns)
        record = TierRecord(
            index=index, code=key.code(), description=setup.describe(key), unknowns=unknowns
        )
        rec.emit("family_generated", index, family=key.code(), unknowns=unknowns, degree=key.degree)
        try:
            column_keys = [setup.key_of(c) for c in columns]
        except sp.PolynomialError:
            record.outcome = "unsupported"
            tiers.append(record)
            continue
        order = sorted(
            range(unknowns),
            key=lambda j: (
                -sum(column_keys[j][len(setup.plain_idx) : len(setup.plain_idx) + flow.n]),
                column_keys[j],
            ),
        )
        columns = [columns[j] for j in order]
        column_keys = [column_keys[j] for j in order]
        column_index = {k: j for j, k in enumerate(column_keys)}

        rows: dict[tuple[int, ...], dict[int, sp.Expr]] = {}
        timed_out = False
        try:
            for j, col in enumerate(columns):
                if time.monotonic() > deadline:
                    timed_out = True
                    break
                for monom, coeff in setup.derivative_terms(col, column_keys[j]).items():
                    rows.setdefault(monom, {})[j] = coeff
        except (sp.PolynomialError, sp.polys.polyerrors.BasePolynomialError):
            record.outcome = "unsupported"
            tiers.append(record)
            rec.emit("family_expanded", index, reason="non_polynomial_derivative")
            stop_reason = "unsupported"
            break
        if timed_out:
            record.outcome = "deadline"
            tiers.append(record)
            stop_reason = "time_budget"
            skipped_tiers = [setup.describe(k) for k in chain[index:]]
            break

        row_keys = list(rows)
        record.equations = len(row_keys)
        rec.emit(
            "determining_equations",
            index,
            equations=len(row_keys),
            unknowns=unknowns,
            ms=int((time.monotonic() - tier_started) * 1000),
        )
        field_ = setup.field
        if row_keys:
            sparse = {
                r: {j: field_.from_sympy(sp.sympify(v)) for j, v in rows[key_].items()}
                for r, key_ in enumerate(row_keys)
            }
            matrix = DomainMatrix(sparse, (len(row_keys), unknowns), field_).to_dense()
            null = matrix.nullspace()
            record.rank = unknowns - null.shape[0]
        else:
            null = DomainMatrix.eye(unknowns, field_).to_dense()
        record.nullity = int(null.shape[0])
        rec.emit(
            "nullspace_computed",
            index,
            rows=len(row_keys),
            cols=unknowns,
            rank=record.rank,
            nullity=record.nullity,
            ms=int((time.monotonic() - tier_started) * 1000),
        )

        algebra = _algebra_vectors(setup, gens, key, column_index, deadline)

        def to_row(vector: dict[int, sp.Expr], field_: Any = field_) -> dict[int, Any]:
            return {j: field_.from_sympy(sp.sympify(v)) for j, v in vector.items()}

        v_slice = slice(len(setup.plain_idx), len(setup.plain_idx) + flow.n)
        column_degree = [sum(k_[v_slice]) for k_ in column_keys]

        def complexity(
            vector: dict[int, sp.Expr], column_degree: list[int] = column_degree
        ) -> tuple[int, int, int]:
            degree = max(column_degree[j] for j in vector)
            return (degree, len(vector), min(vector))

        accepted = rejected = 0
        record.new_directions = len(_new_directions(null, algebra, to_row, field_, unknowns))
        # One direction at a time, simplest first: each accepted constant joins the algebra, so the
        # products that include it (higher-degree multiples) are not reported as further discoveries.
        for _ in range(MAX_PER_TIER):
            directions = _new_directions(null, algebra, to_row, field_, unknowns)
            if not directions or time.monotonic() > deadline:
                break
            vector = min(directions, key=complexity)
            poly_expr, conditions = _primitive(vector, columns)
            shown = sp.expand(poly_expr.subs(setup.back))
            ok, ver = flow.verify(shown)
            symbolic = bool(ver and ver.symbolic_zero)
            rec.emit(
                "verification_completed",
                index,
                passed=bool(ok and symbolic),
                numeric_passed=bool(ok),
                symbolic_zero=symbolic,
                points=ver.numeric_points_checked if ver else 0,
            )
            if not (ok and symbolic):
                rejected += 1
                algebra.append(vector)  # excluded from further consideration, counted
                continue
            accepted += 1
            for cond in conditions:
                for factor, _ in sp.factor_list(cond)[1]:
                    parameter_conditions.add(flow.show(factor))
            gens.append(
                _Gen(
                    id=f"C{len(gens) + 1}",
                    name=f"Constant of motion {len(gens) + 1 - sum(g.kind == 'known' for g in gens)}",
                    shown=shown,
                    poly=sp.expand(poly_expr),
                    kind="new",
                    source="search",
                    tier=index,
                    degree=_momentum_degree(setup, poly_expr),
                    verification=ver,
                )
            )
            rec.emit("candidate_found", index, constant=gens[-1].id, degree=gens[-1].degree)
            algebra = _algebra_vectors(setup, gens, key, column_index, deadline)
        record.accepted, record.rejected = accepted, rejected
        dropped_total += rejected
        record.duration_ms = int((time.monotonic() - tier_started) * 1000)
        tiers.append(record)
        if (
            not maximum_noted
            and not (flow.time_dependent or setup.time_in_rates)
            and lower_rank() >= autonomous_cap
        ):
            maximum_noted = True
            notes.append(
                f"The maximum number of functionally independent constants of an autonomous "
                f"system ({autonomous_cap}) was reached in family {index + 1}."
            )
            rec.emit("family_expanded", index, reason="maximum_rank_reached", rank=autonomous_cap)
        if accepted or rejected:
            rec.emit("family_expanded", index, reason="found" if accepted else "all_rejected")
        else:
            rec.emit("family_expanded", index, reason="no_new_constant")

    if refused and stop_reason == "ladder_exhausted":
        stop_reason = "unknown_cap"

    # -- independence ----------------------------------------------------------------------------------
    ctx = setup.context(gens)
    report_ind = analyze_independence(
        [g.poly for g in gens], ctx, max_possible, deadline + 0.1 * budget.seconds
    )
    rec.emit(
        "independence_checked",
        constants=len(gens),
        rank_lower=report_ind.rank_lower,
        rank_upper=report_ind.rank_upper,
        proved=report_ind.rank_proved,
        relations=len(report_ind.relations),
    )

    constants = [
        DiscoveredConstant(
            id=g.id,
            name=g.name,
            expression_latex=f"{g.id} = {flow.show(g.shown)}",
            kind=g.kind,
            source=g.source,
            tier=g.tier,
            momentum_degree=g.degree,
            independence=(report_ind.status[i] if i < len(report_ind.status) else "unresolved"),
            verification=g.verification,
            reason=g.reason,
        )
        for i, g in enumerate(gens)
    ]
    new = [c for c in constants if c.kind == "new"]
    unexplored = list(dict.fromkeys(refused + skipped_tiers))
    cause: Cause = ""
    if not new:
        if dropped_total:
            cause = "verification_failed"
        elif stop_reason in ("unknown_cap", "time_budget"):
            cause = "resource_limit"
        elif stop_reason == "ladder_exhausted":
            cause = "ansatz_exhausted"
    if flow.params:
        notes.append(
            "Parameters are generic symbols: constants that exist only at special values (for example "
            "resonant frequency ratios) are not searched for; give the values to search at them."
        )
    if parameter_conditions:
        notes.append(
            "Generic parameters: the constants were scaled by factors in the parameters ("
            + ", ".join(sorted(parameter_conditions))
            + "), assumed nonzero; where one vanishes the solution space can differ and was not examined."
        )
    status = Status.OK
    message = _message(len(new), len(tiers), stop_reason, report_ind)
    rec.emit(
        "completed",
        stop=stop_reason,
        cause=cause,
        tiers=len(tiers),
        constants=len(constants),
        new=len(new),
        rejected=dropped_total,
        independent=report_ind.rank_lower,
        peak_mb=_peak_mb(),
        ms=int((time.monotonic() - started) * 1000),
    )
    features = ["discovery", f"discovery:{flow.system}"]
    features.append("discovery:found" if new else "discovery:none-in-family")
    return DiscoveryReport(
        status=status,
        constants=constants,
        tiers=tiers,
        unexplored=unexplored,
        stop_reason=stop_reason,
        cause=cause,
        independence=report_ind,
        parameter_conditions=sorted(parameter_conditions),
        notes=notes + flow.notes,
        events=rec.events,
        features=features,
        message=message,
        peak_memory_mb=_peak_mb(),
        duration_ms=int((time.monotonic() - started) * 1000),
        **{**base, "angles": base["angles"]},
    )


def _message(new: int, tiers: int, stop: str, ind: IndependenceReport) -> str:
    s = "" if new == 1 else "s"
    head = f"{new} new verified constant{s} of motion in the searched families ({tiers} searched)."
    rank = (
        f" Functionally independent: {ind.rank_lower}"
        + ("" if ind.rank_proved else f" to {ind.rank_upper}")
        + (" (proved)." if ind.rank_proved else " (lower bound proved).")
    )
    tail = {
        "maximal_independent_set": " The maximum possible number of independent constants was reached.",
        "ladder_exhausted": " Every family in the ladder was searched; nothing outside them was.",
        "unknown_cap": " Larger families exceeded the size limit and were not searched.",
        "time_budget": " The time budget ended the search; larger families were not searched.",
    }.get(stop, "")
    return head + rank + tail


def _algebra_vectors(
    setup: _Setup,
    gens: list[_Gen],
    key: TierKey,
    column_index: dict[tuple[int, ...], int],
    deadline: float,
) -> list[dict[int, sp.Expr]]:
    """The elements of the family that are polynomials in the known and found constants.

    Products of up to four constants (and the constant 1) are formed up to momentum degree twice the
    family's, because a combination of products of higher degree can cancel down into the family (the
    energy of `h + c L^2` minus `4 c L^2` is `h`). The combinations whose monomials all lie in the
    family are found by an exact nullspace, so a trivial combination is never counted as new."""
    products: list[sp.Expr] = [sp.Integer(1)]
    cap_degree = 2 * key.degree
    count = 0
    for size in range(1, MAX_FACTORS_IN_PRODUCT + 1):
        for combo in itertools.combinations_with_replacement(range(len(gens)), size):
            if sum(gens[i].degree for i in combo) > cap_degree:
                continue
            if count >= MAX_PRODUCTS or time.monotonic() > deadline:
                break
            count += 1
            products.append(sp.Mul(*[gens[i].poly for i in combo]))
    tables: list[dict[tuple[int, ...], sp.Expr]] = []
    for expr in products:
        shifted = sp.expand(expr * setup.shift)
        if not shifted.is_polynomial(*setup.variables):
            continue
        poly = sp.Poly(setup.reduce_angles(shifted), *setup.variables)
        tables.append({tuple(m): c for m, c in poly.terms()})
    outside = sorted({m for t in tables for m in t if m not in column_index})
    if not outside:
        return [{column_index[m]: c for m, c in t.items()} for t in tables if t]
    row = {m: i for i, m in enumerate(outside)}
    field_ = setup.field
    sparse: dict[int, dict[int, Any]] = {}
    for j, t in enumerate(tables):
        for m, c in t.items():
            if m in row:
                sparse.setdefault(row[m], {})[j] = field_.from_sympy(sp.sympify(c))
    null = DomainMatrix(sparse, (len(outside), len(tables)), field_).to_dense().nullspace()
    vectors: list[dict[int, sp.Expr]] = []
    for combo_row in null.to_Matrix().tolist():
        vec: dict[int, sp.Expr] = {}
        for j, coef in enumerate(combo_row):
            if coef == 0:
                continue
            for m, c in tables[j].items():
                col = column_index.get(m)
                if col is not None:
                    vec[col] = vec.get(col, sp.Integer(0)) + coef * c
        vec = {k_: sp.cancel(v_) for k_, v_ in vec.items()}
        vec = {k_: v_ for k_, v_ in vec.items() if v_ != 0}
        if vec:
            vectors.append(vec)
    return vectors


