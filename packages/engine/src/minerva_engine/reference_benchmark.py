"""Multistep problems with answers established independently of Minerva.

Each problem names the textbook or table its expected outcome comes from and is judged by a route that does not
use Minerva's own result path: `mpmath.expm` on explicit matrices, a regularised delta sequence integrated by
quadrature, the quarter-period integral of an oscillator, `mpmath.taylor`, `mpmath.polyroots`, numerical
derivatives, exact Poisson brackets, plain arithmetic. A problem expects either a **correct** answer (the
engine's result must agree with the oracle) or a **refusal** (the engine must not return an `ok` result: the
oracle shows that any such result would be wrong or unjustified).

The problems live in `reference/` (one module per domain; `reference/core.py` documents the fields: oracle,
evidence, tier, pending). `python -m minerva_engine.reference_benchmark [--check] [--tier pr|extended]` runs them.
The outcome of every problem is deterministic and is written to `docs/benchmarks/reference.json`; `--check`
compares the problems of the chosen tier against it and fails on any difference, which is what CI does (the pull
request tier is also run by `test_reference_benchmark.py`). Latencies are recorded but never gated. Rewrite the
files only with `--tier extended`: that runs every problem. Geometry has its own closed-form corpus in
`geometry/benchmark.py`.

Expected answers are written by hand in the judges, with a source locator. Nothing here regenerates an expected
answer from the engine: the JSON stores outcomes, and a changed outcome is a visible diff to review.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path
from typing import Any

from .models import Limits
from .reference import PROBLEMS
from .reference.core import Judge, Problem, verdict
from .service import Engine

__all__ = [
    "PROBLEMS",
    "Judge",
    "Problem",
    "deterministic",
    "main",
    "markdown",
    "run_problems",
    "verdict",
]

_verdict = verdict  # the name the tests use

GOOD = {"correct", "refused_as_expected"}
FAILING = {"wrong", "unsupported_regression", "pending_now_passes"}
KEYS = ("id", "category", "source", "expected", "oracle", "evidence", "tier", "outcome")


def _selected(tier: str) -> list[Problem]:
    return [p for p in PROBLEMS if tier == "extended" or p.tier == "pr"]


def run_problems(engine: Engine | None = None, tier: str = "pr") -> list[dict[str, Any]]:
    engine = engine or Engine(Limits(timeout_seconds=60, max_concurrency=2))
    rows: list[dict[str, Any]] = []
    for p in _selected(tier):
        start = time.monotonic()
        try:
            outcome, detail = p.judge(engine)
        except Exception as exc:  # a crash is a result: it must never be read as a pass
            outcome, detail = "wrong", f"{type(exc).__name__} while judging"
        if p.pending is not None:
            # Expected not to pass yet: a pass is a failure until the problem is promoted, a miss is "pending".
            outcome = "pending_now_passes" if outcome in GOOD else "pending"
        rows.append(
            {
                "id": p.id,
                "category": p.category,
                "source": p.source,
                "expected": p.expected,
                "oracle": p.oracle,
                "evidence": p.evidence,
                "tier": p.tier,
                "pending": p.pending,
                "outcome": outcome,
                "detail": detail,
                "latency_ms": int((time.monotonic() - start) * 1000),
            }
        )
    return rows


def deterministic(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    out = []
    for r in rows:
        row = {k: r[k] for k in KEYS}
        if r.get("pending"):
            row["pending"] = r["pending"]
        out.append(row)
    return out


def markdown(rows: list[dict[str, Any]]) -> str:
    pending = sum(r["outcome"] == "pending" for r in rows)
    lines = [
        "# Reference problems",
        "",
        "Generated by `python -m minerva_engine.reference_benchmark --tier extended`; outcomes are deterministic, "
        "latencies are not gated. Expected answers are written by hand with a source locator (see "
        "`packages/engine/src/minerva_engine/reference/`); this file only records what the engine did.",
        "",
        f"{sum(r['outcome'] in GOOD for r in rows)} of {len(rows)} as expected; "
        f"wrong: {sum(r['outcome'] == 'wrong' for r in rows)}; "
        f"unsupported where an answer is expected: {sum(r['outcome'] == 'unsupported_regression' for r in rows)}; "
        f"pending (known gap, not counted as correct): {pending}.",
        "",
        "| Problem | Category | Expected | Outcome | Oracle | Evidence | Tier | Source | ms |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    lines += [
        f"| `{r['id']}` | {r['category']} | {r['expected']} | {r['outcome']}"
        f"{' (' + r['pending'] + ')' if r.get('pending') else ''} | {r['oracle']} | {r['evidence']} | "
        f"{r['tier']} | {r['source']} | {r['latency_ms']} |"
        for r in rows
    ]
    return "\n".join(lines) + "\n"


def _tier_of(argv: list[str]) -> str:
    if "--tier" in argv:
        value = argv[argv.index("--tier") + 1 :][:1]
        if value and value[0] in ("pr", "extended"):
            return value[0]
        raise SystemExit("--tier must be pr or extended")
    return "pr" if "--check" in argv else "extended"


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parents[4]
    json_path, md_path = (
        root / "docs/benchmarks/reference.json",
        root / "docs/reference-benchmark.md",
    )
    tier = _tier_of(argv)
    rows = run_problems(tier=tier)
    bad = [r for r in rows if r["outcome"] in FAILING]
    if "--check" in argv:
        recorded = json.loads(json_path.read_text())["problems"] if json_path.exists() else None
        wanted = (
            None
            if recorded is None
            else [r for r in recorded if tier == "extended" or r["tier"] == "pr"]
        )
        if wanted != deterministic(rows):
            print("reference outcomes differ from docs/benchmarks/reference.json", file=sys.stderr)
            return 1
    elif tier != "extended":
        print("rewrite the report with --tier extended (every problem)", file=sys.stderr)
        return 2
    else:
        json_path.write_text(json.dumps({"problems": deterministic(rows)}, indent=2) + "\n")
        md_path.write_text(markdown(rows))
    for r in bad:
        print(f"{r['id']}: {r['outcome']} ({r['detail']})", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
