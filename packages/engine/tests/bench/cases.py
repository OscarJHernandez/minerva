"""Generated benchmark cases: a base system, a seeded exact canonical map, the transformed Hamiltonian and
invariants, and every check that makes the reference trustworthy.

At generation, exactly (rational arithmetic, no sampling):
  1. the map is symplectic (`M^T J M = J`) and preserves the canonical brackets of the coordinates;
  2. every transformed invariant satisfies `{I', H'} = 0` in the new variables;
  3. the reference functional rank is computed from the Jacobian.

A case stores its seed, generator version, recipe (the exact matrices) and parameters, so it can be
regenerated byte for byte (`scripts/bench_invariants.py --check`). `EngineInput` is the only thing handed
to Minerva: the Hamiltonian and the variable names. The reference invariants never leave this module.
"""

from __future__ import annotations

import json
import random
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import sympy as sp

from .descriptors import Descriptor, describe, frontiers
from .symplectic import (
    SEPARABLE_KINDS,
    bracket,
    canonical_brackets_preserved,
    map_from_recipe,
    phase_symbols,
    random_map,
    transform,
)
from .systems import Base, build_base

GENERATOR_VERSION = 1
FIXTURES = Path(__file__).parent / "fixtures"
MAX_TERMS = {2: 36, 3: 70}
MAX_HEIGHT = 60  # largest numerator or denominator in the transformed Hamiltonian


@dataclass(frozen=True)
class EngineInput:
    """All that discovery is given."""

    hamiltonian_latex: str
    coordinates: list[str]
    momenta: list[str]


@dataclass
class Reference:
    name: str
    expr: sp.Expr
    descriptor: Descriptor


@dataclass
class Case:
    id: str
    kind: str  # discovery | negative_control
    base: str
    source: str
    seed: int
    steps: int
    mixing: bool
    recipe: list[dict[str, Any]]
    n: int
    H: sp.Expr
    refs: list[Reference]
    ref_rank: int
    params: dict[str, str]
    parent: str | None = None
    perturbation: dict[str, Any] | None = None
    broken: dict[str, bool] = field(default_factory=dict)  # negative controls: {I, H'} != 0

    @property
    def q(self) -> list[sp.Symbol]:
        return phase_symbols(self.n)[0]

    @property
    def p(self) -> list[sp.Symbol]:
        return phase_symbols(self.n)[1]

    def engine_input(self) -> EngineInput:
        return EngineInput(
            hamiltonian_latex=str(sp.latex(self.H)),
            coordinates=[s.name for s in self.q],
            momenta=[s.name for s in self.p],
        )

    def cyclic(self) -> set[int]:
        return cyclic_indices(self.H, self.q, self.p)


def cyclic_indices(H: sp.Expr, q: list[sp.Symbol], p: list[sp.Symbol]) -> set[int]:
    """Coordinates that appear in no derivative of H, hence in no equation of motion."""
    rates = [sp.diff(H, v) for v in [*q, *p]]
    return {i for i, qi in enumerate(q) if not any(qi in r.free_symbols for r in rates)}


# --- reference rank, independently of the engine -------------------------------------------------------
def functional_rank(exprs: list[sp.Expr], q: list[sp.Symbol], p: list[sp.Symbol]) -> int:
    """Largest exact Jacobian rank at a few rational points: a lower bound of the generic rank, and the
    generic rank itself except at unlucky points (several are tried)."""
    if not exprs:
        return 0
    z = list(q) + list(p)
    jac = sp.Matrix([[sp.diff(e, v) for v in z] for e in exprs])
    best = 0
    rng = random.Random(7)
    for _ in range(6):
        point = {v: sp.Rational(rng.randint(2, 19), rng.randint(2, 11)) for v in z}
        try:
            value = jac.subs(point)
            if value.has(sp.zoo, sp.nan, sp.oo):
                continue
            best = max(best, int(value.rank()))
        except (ZeroDivisionError, TypeError):
            continue
    return best


def _height_ok(expr: sp.Expr) -> bool:
    for atom in expr.atoms(sp.Rational):
        if abs(atom.p) > MAX_HEIGHT or abs(atom.q) > MAX_HEIGHT:
            return False
    return True


def _algebraic(expr: sp.Expr) -> bool:
    """A fractional power somewhere (a square root): outside the polynomial machinery."""
    return any(
        node.is_Pow and node.exp.is_Rational and not node.exp.is_Integer
        for node in sp.preorder_traversal(expr)
    )


def _terms(expr: sp.Expr) -> int:
    return len(sp.Add.make_args(sp.expand(expr)))


# --- building -------------------------------------------------------------------------------------------
def build_case(base_name: str, seed: int, steps: int, *, mixing: bool = True) -> Case:
    """Deterministic in (base_name, seed, steps, mixing, GENERATOR_VERSION)."""
    base_rng = random.Random(f"{GENERATOR_VERSION}:{base_name}:{seed}:base")
    base: Base = build_base(base_name, base_rng)
    q, p = phase_symbols(base.n)
    kinds = None if mixing else SEPARABLE_KINDS
    attempt = 0
    while True:
        map_rng = random.Random(f"{GENERATOR_VERSION}:{base_name}:{seed}:{steps}:{attempt}")
        if steps == 0:
            m, recipe = sp.eye(2 * base.n), []
        elif kinds is None:
            m, recipe = random_map(base.n, map_rng, steps)
        else:
            m, recipe = random_map(base.n, map_rng, steps, kinds)
        H = transform(base.H, m, q, p) if not _algebraic(base.H) else None
        if H is None:  # algebraic base: the map must be the identity, kept exact
            H, m, recipe = base.H, sp.eye(2 * base.n), []
        if _terms(H) <= MAX_TERMS[base.n] and _height_ok(H):
            break
        attempt += 1
        if attempt > 40:
            raise RuntimeError(f"no map of complexity within the caps for {base_name}/{seed}")
    # 1. the map is canonical, checked on the brackets of the coordinates themselves
    assert canonical_brackets_preserved(m, q, p)
    invariants = []
    for label, inv in base.invariants:
        new = inv if _algebraic(inv) or _algebraic(H) else transform(inv, m, q, p)
        # 2. independent confirmation in the new variables
        if sp.simplify(bracket(new, H, q, p)) != 0:
            raise AssertionError(f"{label} is not conserved after the transformation")
        invariants.append((label, new))
    cyclic = cyclic_indices(H, q, p)
    fr = frontiers(H, invariants, q, p, cyclic) if not _algebraic(H) else {}
    refs = []
    for label, inv in invariants:
        d = describe(inv, q, p, cyclic)
        if label in fr:
            d.frontier = fr[label]
            d.scope = "span of 1, H, the invariants and their pairwise products"
        refs.append(Reference(label, inv, d))
    rank = functional_rank([H, *[e for _, e in invariants]], q, p)
    ident = f"{base_name}.s{seed}.k{steps}" + ("" if mixing else ".sep")
    return Case(
        id=ident,
        kind="discovery",
        base=base_name,
        source=base.source,
        seed=seed,
        steps=steps,
        mixing=mixing,
        recipe=recipe,
        n=base.n,
        H=H,
        refs=refs,
        ref_rank=rank,
        params=base.params,
    )


PERTURBATIONS = [
    lambda q, p: q[0] ** 2 * q[-1],
    lambda q, p: q[-1] ** 3,
    lambda q, p: q[0] * q[-1] ** 2,
    lambda q, p: q[0] ** 4,
    lambda q, p: q[0] * p[-1],
    lambda q, p: p[0] * q[-1] ** 2,
]


def negative_control(case: Case, index: int, eps: sp.Rational) -> Case:
    """The same case with `eps * term` added to H. Whether a reference invariant survives is computed
    (`{I, H'}`), never assumed: a perturbation need not break every invariant."""
    q, p = case.q, case.p
    term = sp.expand(PERTURBATIONS[index](q, p))
    H2 = sp.expand(case.H + eps * term)
    broken = {r.name: sp.simplify(bracket(r.expr, H2, q, p)) != 0 for r in case.refs}
    survivors = [r.expr for r in case.refs if not broken[r.name]]
    return Case(
        id=f"{case.id}.neg{index}",
        kind="negative_control",
        base=case.base,
        source=case.source,
        seed=case.seed,
        steps=case.steps,
        mixing=case.mixing,
        recipe=case.recipe,
        n=case.n,
        H=H2,
        refs=case.refs,
        ref_rank=functional_rank([H2, *survivors], q, p),
        params=case.params,
        parent=case.id,
        perturbation={"index": index, "eps": str(eps), "term": str(term)},
        broken=broken,
    )


# --- fixtures -------------------------------------------------------------------------------------------
def to_json(case: Case) -> dict[str, Any]:
    return {
        "id": case.id,
        "generator_version": GENERATOR_VERSION,
        "kind": case.kind,
        "base": case.base,
        "source": case.source,
        "seed": case.seed,
        "steps": case.steps,
        "mixing": case.mixing,
        "n": case.n,
        "params": case.params,
        "recipe": case.recipe,
        "hamiltonian": str(case.H),
        "hamiltonian_latex": case.engine_input().hamiltonian_latex,
        "reference_rank": case.ref_rank,
        "parent": case.parent,
        "perturbation": case.perturbation,
        "broken": case.broken,
        "references": [
            {
                "name": r.name,
                "expr": str(r.expr),
                "representable": r.descriptor.representable,
                "momentum_degree": r.descriptor.momentum_degree,
                "power_range": list(r.descriptor.power_range),
                "terms": r.descriptor.terms,
                "ops": r.descriptor.ops,
                "frontier": r.descriptor.frontier,
                "frontier_scope": r.descriptor.scope,
                "reason": r.descriptor.reason,
            }
            for r in case.refs
        ],
    }


def from_json(data: dict[str, Any]) -> Case:
    n = int(data["n"])
    q, p = phase_symbols(n)
    local = {s.name: s for s in [*q, *p]}
    refs = [
        Reference(
            r["name"],
            sp.sympify(r["expr"], locals=local),
            Descriptor(
                r["representable"],
                r["momentum_degree"],
                tuple(r["power_range"]),
                r["terms"],
                r["ops"],
                [(f[0], f[1], f[2]) for f in r["frontier"]] if r["frontier"] else None,
                r["frontier_scope"],
                r["reason"],
            ),
        )
        for r in data["references"]
    ]
    return Case(
        id=data["id"],
        kind=data["kind"],
        base=data["base"],
        source=data["source"],
        seed=data["seed"],
        steps=data["steps"],
        mixing=data["mixing"],
        recipe=data["recipe"],
        n=n,
        H=sp.sympify(data["hamiltonian"], locals=local),
        refs=refs,
        ref_rank=data["reference_rank"],
        params=data["params"],
        parent=data["parent"],
        perturbation=data["perturbation"],
        broken=data["broken"],
    )


# (base, seed, steps, mixing, negative-control perturbation indices with their eps)
FIXED_SPECS: list[tuple[str, int, int, bool, list[tuple[int, str]]]] = [
    ("free2", 1, 0, True, []),
    ("free2", 2, 2, True, []),
    ("osc2_iso", 1, 0, True, [(0, "1/3"), (3, "1/2")]),
    ("osc2_iso", 2, 2, True, [(1, "1/2")]),
    ("osc2_iso", 3, 3, True, []),
    ("osc2_iso", 4, 2, False, []),
    ("osc2_res", 1, 0, True, [(0, "1/4")]),
    ("osc2_res", 2, 2, True, []),
    ("osc2_aniso", 1, 2, True, []),
    ("quartic_sep", 1, 1, False, []),
    ("central_quartic", 1, 2, True, []),
    ("sw", 1, 0, True, []),
    ("sw", 2, 2, True, []),
    ("sw", 3, 2, False, []),
    ("func_inv", 1, 2, True, []),
    ("func_inv_rot", 1, 2, True, []),
    ("sep_sum", 1, 2, True, []),
    ("sep_sum", 2, 1, False, [(4, "1/3")]),
    ("cyclic_sep", 1, 2, True, []),
    ("kepler_cartesian", 1, 0, True, []),
    ("osc3_iso", 1, 1, False, []),
]


def build_fixed() -> list[Case]:
    out: list[Case] = []
    for base, seed, steps, mixing, negatives in FIXED_SPECS:
        case = build_case(base, seed, steps, mixing=mixing)
        out.append(case)
        for index, eps in negatives:
            out.append(negative_control(case, index, sp.Rational(eps)))
    return out


def fixed_path() -> Path:
    return FIXTURES / "fixed_seed.json"


def write_fixed() -> int:
    data = [to_json(c) for c in build_fixed()]
    fixed_path().write_text(json.dumps(data, indent=1, sort_keys=True) + "\n")
    return len(data)


def load_fixed() -> list[Case]:
    return [from_json(d) for d in json.loads(fixed_path().read_text())]


def rebuild(case: Case) -> Case:
    """Regenerate a stored case from its seed."""
    if case.kind == "negative_control":
        assert case.perturbation is not None and case.parent is not None
        parent = build_case(case.base, case.seed, case.steps, mixing=case.mixing)
        return negative_control(
            parent, case.perturbation["index"], sp.Rational(case.perturbation["eps"])
        )
    return build_case(case.base, case.seed, case.steps, mixing=case.mixing)


def map_matrix(case: Case) -> sp.Matrix:
    return map_from_recipe(case.recipe, case.n)
