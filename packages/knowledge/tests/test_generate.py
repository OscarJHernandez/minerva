"""The generator only writes candidates that pass every filter, and its output is reproducible."""

from pathlib import Path

import pytest
import yaml
from minerva_engine import Engine
from minerva_knowledge import KnowledgeBase, load_entries
from minerva_knowledge.__main__ import main
from minerva_knowledge.checks import run_check
from minerva_knowledge.generate import (
    ALG,
    OUTPUT_FILES,
    SEEDS,
    TRANSFORMS,
    TRIG,
    Generated,
    Seed,
    build,
    entries_dir,
    render_all,
    stale_files,
    write,
)


def one(engine: Engine, **kwargs: object) -> Generated:
    defaults: dict[str, object] = {
        "id": "test.candidate",
        "title": "Candidate",
        "chapter": TRIG,
        "section": "multiple",
    }
    return build([Seed(**{**defaults, **kwargs})], engine)  # type: ignore[arg-type]


def reason(result: Generated) -> str:
    assert not result.entries, "expected the seed to be rejected"
    assert len(result.rejected) == 1
    return result.rejected[0].reason


@pytest.fixture(scope="module")
def generated(engine: Engine) -> Generated:
    return build(SEEDS, engine)


# --- the committed seeds ------------------------------------------------------------------------
def test_every_committed_seed_is_accepted(generated: Generated) -> None:
    assert generated.rejected == []
    assert generated.count == len(SEEDS)


def test_committed_files_are_current(generated: Generated) -> None:
    """Edit the seed and regenerate, never the YAML: a stale file would otherwise slip through."""
    assert stale_files(generated) == []


def test_generation_is_deterministic(engine: Engine, generated: Generated) -> None:
    assert render_all(build(SEEDS, engine)) == render_all(generated)


def test_generated_files_are_marked(generated: Generated) -> None:
    for name in OUTPUT_FILES.values():
        text = (entries_dir() / name).read_text(encoding="utf-8")
        assert text.startswith("# Generated by `python -m minerva_knowledge generate`")


def test_level_matches_what_the_checker_established(generated: Generated) -> None:
    """`symbolic` only with a symbolic zero; otherwise the entry must say `numeric`."""
    by_id = {e.id: e for e in load_entries()}
    for entries in generated.entries.values():
        for data in entries:
            entry = by_id[data["id"]]
            report = run_check(entry)
            assert report.passed, entry.id
            assert entry.verification == ("symbolic" if report.symbolic_proof else "numeric")


def test_generated_entries_are_original_rules_without_copied_text(generated: Generated) -> None:
    for entries in generated.entries.values():
        for data in entries:
            assert data["provenance"] == "original"
            assert data["kind"] == "identity"
            assert data["rule"]["id"] == data["id"]
            if "reference" in data:
                assert data["reference"]["source"] == "DLMF"
                assert data["reference"]["locator"].startswith("§")


def test_every_generated_entry_is_in_the_knowledge_base(
    kb: KnowledgeBase, generated: Generated
) -> None:
    for entries in generated.entries.values():
        for data in entries:
            entry = kb.get(data["id"])
            assert entry is not None and entry.rule is not None
            assert entry.chapter == data["chapter"]


# --- candidates that must be rejected -----------------------------------------------------------
def test_wrong_right_hand_side_is_rejected(engine: Engine) -> None:
    """sin(2a) is not 2 sin(a): the independent check, not the seed, decides."""
    assert "filter 4" in reason(one(engine, lhs="sin(2*a)", rhs="2*sin(a)"))


def test_off_by_a_sign_is_rejected(engine: Engine) -> None:
    assert "filter 4" in reason(one(engine, lhs="cos(2*a)", rhs="cos(a)**2 + sin(a)**2"))


def test_a_wrong_transform_cannot_vouch_for_itself(
    engine: Engine, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The right-hand side is a proposal: a transform that returns nonsense is caught by the check."""
    monkeypatch.setitem(TRANSFORMS, "off_by_one", lambda expr: expr + 1)
    assert "filter 4" in reason(one(engine, lhs="sin(3*a)", transform="off_by_one"))


def test_left_hand_side_that_evaluates_away_is_rejected(engine: Engine) -> None:
    assert "no variables" in reason(one(engine, lhs="sin(0)", rhs="0"))


def test_identical_sides_are_rejected(engine: Engine) -> None:
    assert "identical" in reason(one(engine, lhs="sin(a)", rhs="sin(a)"))


def test_right_hand_side_with_a_new_variable_is_rejected(engine: Engine) -> None:
    assert "new ones" in reason(one(engine, lhs="sin(a)", rhs="sin(b)"))


def test_duplicate_of_a_handbook_rule_is_rejected_after_renaming_variables(
    engine: Engine,
) -> None:
    """trig.pythagorean already states sin(a)**2 + cos(a)**2 = 1; `t` instead of `a` changes nothing."""
    assert "filter 3" in reason(one(engine, lhs="sin(t)**2 + cos(t)**2", rhs="1"))


def test_duplicate_seed_id_is_rejected(engine: Engine) -> None:
    seed = Seed("test.twice", "Twice", ALG, "binomial", "(a + b)**5", transform="expand")
    result = build([seed, seed], engine)
    assert len(result.entries[ALG]) == 1
    assert [r.reason for r in result.rejected] == ["duplicate seed id"]


@pytest.mark.parametrize(
    "kwargs",
    [
        {"lhs": "sin(a)"},  # neither transform nor rhs
        {"lhs": "sin(a)", "transform": "expand_trig", "rhs": "sin(a)"},  # both
        {"lhs": "sin(a)", "transform": "no_such_transform"},
    ],
)
def test_malformed_seed_is_rejected(engine: Engine, kwargs: dict[str, str]) -> None:
    assert reason(one(engine, **kwargs))


def test_unparsable_side_is_rejected(engine: Engine) -> None:
    assert "does not parse" in reason(one(engine, lhs="sin(", rhs="1"))


@pytest.mark.parametrize(
    "where", [{"section": "no_such_section"}, {"chapter": "math.no_such_chapter"}]
)
def test_unknown_chapter_or_section_is_rejected(engine: Engine, where: dict[str, str]) -> None:
    assert "unknown chapter or section" in reason(
        one(engine, lhs="sin(3*a)", transform="expand_trig", **where)
    )


# --- output ---------------------------------------------------------------------------------------
def test_rejected_seeds_write_nothing_for_them(engine: Engine, tmp_path: Path) -> None:
    result = one(engine, lhs="sin(2*a)", rhs="2*sin(a)")
    (tmp_path / "entries").mkdir()
    paths = write(result, data_dir=tmp_path)
    assert {p.name for p in paths} == set(OUTPUT_FILES.values())
    for path in paths:
        assert yaml.safe_load(path.read_text(encoding="utf-8")) == []


def test_written_yaml_round_trips_to_the_same_entries(generated: Generated, tmp_path: Path) -> None:
    (tmp_path / "entries").mkdir()
    for path in write(generated, data_dir=tmp_path):
        chapter = next(c for c, n in OUTPUT_FILES.items() if n == path.name)
        assert yaml.safe_load(path.read_text(encoding="utf-8")) == generated.entries.get(
            chapter, []
        )


def test_stale_files_detects_a_changed_file(generated: Generated, tmp_path: Path) -> None:
    (tmp_path / "entries").mkdir()
    write(generated, data_dir=tmp_path)
    assert stale_files(generated, data_dir=tmp_path) == []
    first = tmp_path / "entries" / next(iter(OUTPUT_FILES.values()))
    first.write_text(first.read_text(encoding="utf-8") + "# edited by hand\n", encoding="utf-8")
    assert stale_files(generated, data_dir=tmp_path) == [first.name]
    first.unlink()
    assert stale_files(generated, data_dir=tmp_path) == [first.name]


def test_cli_check_passes_on_the_committed_files() -> None:
    assert main(["generate", "--check"]) == 0


def test_cli_rejects_unknown_command(capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["frobnicate"]) == 2
    assert "usage" in capsys.readouterr().err
