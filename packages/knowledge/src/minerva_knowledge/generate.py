"""Generate handbook identity entries from seeds, and verify every one before it is written.

A seed names an identity's left-hand side and either a SymPy transform that derives the right-hand
side (`expand_trig`, `expand`, `factor`, `tr8`, `tr9`) or an explicit right-hand side. The
transform is only a *proposal*: nothing is written unless the candidate passes every filter below,
and the checks that decide (`checks.run_check`, the engine's rule application) never use the
transform, so a wrong proposal cannot vouch for itself.

Filters, in order; a candidate failing any one is rejected with its reason:

1. both sides survive a text round trip (`parse_text(text) == expr`), so the rule means what is stored;
2. the entry validates against the schema (`models.Entry`);
3. it is not a duplicate of an existing rule (same sides after renaming variables);
4. `checks.run_check` passes. The level is `symbolic` only when a symbolic zero was found, else `numeric`;
5. the engine reports the rule APPLICABLE on its own left-hand side.

Edit the seeds here, never the generated YAML: `python -m minerva_knowledge generate` rewrites it and
`generate --check` fails when the committed files are stale.
"""

