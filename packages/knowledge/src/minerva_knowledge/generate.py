@dataclass(frozen=True)
class Rejection:
    seed_id: str
    reason: str


@dataclass
class Generated:
    entries: dict[str, list[dict[str, Any]]] = field(default_factory=dict)  # chapter -> entries
    rejected: list[Rejection] = field(default_factory=list)

    @property
    def count(self) -> int:
        return sum(len(v) for v in self.entries.values())


def _rule_key(lhs: sp.Expr, rhs: sp.Expr) -> tuple[sp.Expr, sp.Expr]:
    """Same sides after renaming variables in alphabetical order: a duplicate detector."""
    names = sorted(s.name for s in lhs.free_symbols)
    mapping = {sp.Symbol(n): sp.Symbol(f"_v{i}") for i, n in enumerate(names)}
    return lhs.xreplace(mapping), rhs.xreplace(mapping)


def _entry_data(
    seed: Seed, lhs: str, rhs: str, variables: list[str], verification: str
) -> dict[str, Any]:
    data: dict[str, Any] = {
        "id": seed.id,
        "title": seed.title,
        "kind": "identity",
        "chapter": seed.chapter,
        "section": seed.section,
        "verification": verification,
    }
    if seed.validity:
        data["validity"] = seed.validity
    data["rule"] = {"id": seed.id, "lhs": lhs, "rhs": rhs, "variables": variables}
    if seed.dlmf:
        data["reference"] = {
            "source": "DLMF",
            "locator": f"§{seed.dlmf}",
            "url": f"https://dlmf.nist.gov/{seed.dlmf.split('(')[0]}",
        }
    data["keywords"] = list(seed.keywords)
    data["provenance"] = "original"
    return data


def _candidate(
    seed: Seed,
    engine: Engine,
    known: set[tuple[sp.Expr, sp.Expr]],
    sections: dict[str, set[str]],
) -> dict[str, Any]:
    """Return the entry data for `seed`, or raise ValueError naming the filter it failed."""
    if (seed.transform is None) == (seed.rhs is None):
        raise ValueError("a seed needs exactly one of `transform` and `rhs`")
    try:
        lhs = parse_text(seed.lhs)
        if seed.transform is not None:
            if seed.transform not in TRANSFORMS:
                raise ValueError(f"unknown transform {seed.transform!r}")
            rhs = TRANSFORMS[seed.transform](lhs)
        else:
            rhs = parse_text(str(seed.rhs))
    except MinervaMathError as exc:
        raise ValueError(f"does not parse: {exc}") from exc

    variables = sorted(s.name for s in lhs.free_symbols)
    if not variables or {s.name for s in rhs.free_symbols} - set(variables):
        raise ValueError("left-hand side has no variables, or the right-hand side adds new ones")
    if lhs == rhs:
        raise ValueError("both sides are identical")

    # 1. text round trip
    lhs_text, rhs_text = sp.sstr(lhs), sp.sstr(rhs)
    try:
        if parse_text(lhs_text) != lhs or parse_text(rhs_text) != rhs:
            raise ValueError("filter 1: a side does not survive a text round trip")
    except MinervaMathError as exc:
        raise ValueError(f"filter 1: a side cannot be re-parsed: {exc}") from exc

    # 2. schema, and the chapter and section must exist (the loader would reject them later)
    if seed.section not in sections.get(seed.chapter, set()):
        raise ValueError(f"filter 2: unknown chapter or section {seed.chapter!r}/{seed.section!r}")
    try:
        entry = Entry(**_entry_data(seed, lhs_text, rhs_text, variables, "numeric"))
    except ValidationError as exc:
        raise ValueError(f"filter 2: schema: {exc.errors()[0]['msg']}") from exc

    # 3. duplicates
    key = _rule_key(lhs, rhs)
    if key in known:
        raise ValueError("filter 3: duplicate of an existing rule")

    # 4. the declared check, decided independently of the transform
    report = run_check(entry)
    if not report.passed:
        raise ValueError(f"filter 4: check failed: {report.detail}")
    verification = "symbolic" if report.symbolic_proof else "numeric"
    data = _entry_data(seed, lhs_text, rhs_text, variables, verification)
    entry = Entry(**data)

    # 5. the engine can apply the rule to its own left-hand side
    assert entry.rule is not None  # noqa: S101 - set above
    result = engine.apply_rules(ExpressionInput(input=lhs_text, format="text"), [entry.rule])
    applied = [a for a in result.applications if a.rule_id == entry.id]
    if (
        result.status is not Status.OK
        or not applied
        or applied[0].applicability is not Applicability.APPLICABLE
    ):
        outcome = applied[0].applicability.value if applied else result.status.value
        raise ValueError(f"filter 5: does not apply to its own left-hand side ({outcome})")

    known.add(key)
    return data


def build(
    seeds: Sequence[Seed], engine: Engine, existing: Sequence[Entry] | None = None
) -> Generated:
    """Run every seed through the filters. `existing` are the hand-written entries to avoid copying."""
    seed_ids = {s.id for s in seeds}
    known: set[tuple[sp.Expr, sp.Expr]] = set()
    sections = {c.id: {sec.id for sec in c.sections} for c in load_chapters()}
    for entry in existing if existing is not None else load_entries():
        if entry.rule is not None and entry.id not in seed_ids:
            known.add(_rule_key(parse_text(entry.rule.lhs), parse_text(entry.rule.rhs)))

    result = Generated()
    ids: set[str] = set()
    for seed in seeds:
        if seed.id in ids:
            result.rejected.append(Rejection(seed.id, "duplicate seed id"))
            continue
        ids.add(seed.id)
        try:
            data = _candidate(seed, engine, known, sections)
        except ValueError as exc:
            result.rejected.append(Rejection(seed.id, str(exc)))
            continue
        result.entries.setdefault(seed.chapter, []).append(data)
    return result


def render(entries: list[dict[str, Any]]) -> str:
    body = yaml.safe_dump(entries, sort_keys=False, allow_unicode=True, width=10_000)
    return HEADER + body


def render_all(generated: Generated) -> dict[str, str]:
    """File name -> content, for every output file (an empty chapter renders as an empty list)."""
    return {
        name: render(generated.entries.get(chapter, [])) for chapter, name in OUTPUT_FILES.items()
    }


def entries_dir(data_dir: Path = DATA_DIR) -> Path:
    return data_dir / "entries"


def write(generated: Generated, data_dir: Path = DATA_DIR) -> list[Path]:
    paths = []
    for name, text in render_all(generated).items():
        path = entries_dir(data_dir) / name
        path.write_text(text, encoding="utf-8")
        paths.append(path)
    return paths


def stale_files(generated: Generated, data_dir: Path = DATA_DIR) -> list[str]:
    """Names of generated files whose committed content differs from a fresh generation."""
    stale = []
    for name, text in render_all(generated).items():
        path = entries_dir(data_dir) / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
    return stale
