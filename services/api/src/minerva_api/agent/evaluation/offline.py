BACKED = ("from_tool", "checked", "conditional")
LAGRANGIAN_LATEX = (
    r"\frac12 m R^2 (\dot{\theta}^2 + \sin^2(\theta) \dot{\phi}^2) - m g R \cos(\theta)"
)
LAGRANGIAN_TEXT = "1/2*m*R^2*(theta_dot^2 + sin(theta)^2*phi_dot^2) - m*g*R*cos(theta)"
THETA_RIGHT = r"\ddot\theta = \sin\theta\cos\theta\,\dot\phi^2 + \frac{g}{R}\sin\theta"
THETA_WRONG = r"\ddot\theta = \sin\theta\cos\theta\,\dot\phi^2 - \frac{g}{R}\sin\theta"
PHI_RIGHT = r"\ddot\phi = -2\cot\theta\,\dot\theta\dot\phi"
P_PHI = r"p_\phi = mR^2\sin^2\theta\,\dot\phi"
ENERGY = r"E=\frac12 mR^2(\dot\theta^2+\sin^2\theta\,\dot\phi^2)+mgR\cos\theta"
PENDULUM_ANSWER = (
    f"With $\\theta$ and $\\phi$ as coordinates:\n\n$${THETA_RIGHT}$$\n\n$${PHI_RIGHT}$$\n\n"
    f"$\\phi$ is cyclic, so ${P_PHI}$ is conserved, and so is ${ENERGY}$."
)
PENDULUM_MUST = [THETA_RIGHT, PHI_RIGHT, P_PHI, ENERGY]

# A recorded failure: the model chose analyze_lagrangian and wrote the velocities as `Xdot`, then sent the
# same text with markdown-escaped `\*`, then repeated its first call. The equations below are derived by hand
# from L (mass matrix [[M+m,0,m cos a],[0,M+m,m sin a],[m cos a,m sin a,m]], determinant M m (M+m): the
# accelerations are X'' = 0, Y'' = -g, s'' = 0), not generated by the engine.
WEDGE_PLAIN = (
    "1/2*(M+m)*(Xdot^2 + Ydot^2) + 1/2*m*sdot^2 + m*sdot*(Xdot*cos(alpha) + Ydot*sin(alpha))"
    " - (M+m)*g*Y - m*g*s*sin(alpha)"
)
WEDGE_ESCAPED = WEDGE_PLAIN.replace("*", r"\*")
WEDGE_CANONICAL = (
    "1/2*(M+m)*(X_dot^2 + Y_dot^2) + 1/2*m*s_dot^2 + m*s_dot*(X_dot*cos(alpha) + Y_dot*sin(alpha))"
    " - (M+m)*g*Y - m*g*s*sin(alpha)"
)
WEDGE_COORDINATES = ["X", "Y", "s"]
WEDGE_X = r"\ddot{X} = 0"
WEDGE_Y = r"\ddot{Y} = -g"
WEDGE_S = r"\ddot{s} = 0"
WEDGE_EL_X = r"(M+m)\ddot{X} + m\ddot{s}\cos\alpha = 0"
WEDGE_ANSWER = (
    "With $X$, $Y$ and $s$ as coordinates the Euler-Lagrange equation for $X$ is\n\n"
    f"$${WEDGE_EL_X}$$\n\nand solving all three for the accelerations gives\n\n"
    f"$${WEDGE_X}$$\n\n$${WEDGE_Y}$$\n\n$${WEDGE_S}$$"
)
WEDGE_MUST = [WEDGE_X, WEDGE_Y, WEDGE_S]


@dataclass
class Trajectory:
    id: str
    category: str
    description: str
    message: str
    replies: Callable[[], list[list[Chunk]]]
    routing: bool = False
    expect_tool: str | None = None
    must_back: list[str] = field(default_factory=list)  # claims that must end up backed
    must_not_back: list[str] = field(default_factory=list)  # claims that must NOT be backed
    # Run on the unmodified code too: false for trajectories that describe behaviour only the fixes make
    # possible (a router-chosen first call, a model that now succeeds at once).
    comparable: bool = True
    # A known failure that a planned change must fix: the reason it fails today. A pending trajectory is
    # allowed to end incorrect and must not end correct (strict): when it passes, remove the marker.
    pending: str = ""


def _bad_call(**extra: Any) -> list[Chunk]:
    return [Chunk(tool_calls=[ToolCall("simplify", {}, **extra)])]


